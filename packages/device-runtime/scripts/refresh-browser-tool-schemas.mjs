#!/usr/bin/env node
// Refresh chrome-devtools-mcp static input schemas + per-tool sha256 hashes.
// Spawns the pinned sidecar from node_modules/.bin, fetches tools/list,
// writes both `schemas` AND `hashes` into the artifact the provider relies
// on for drift detection.
//
// Run manually when bumping PINNED_VERSION:
//   node packages/device-runtime/scripts/refresh-browser-tool-schemas.mjs
//
// Pure JS (.mjs) — `node` can spawn this directly. The previous .ts version
// failed with ERR_UNKNOWN_FILE_EXTENSION.

import { Client } from "@modelcontextprotocol/sdk/client/index.js"
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js"
import { createHash } from "node:crypto"
import { existsSync, writeFileSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const PKG_DIR = resolve(here, "..")
const OUT = resolve(
  PKG_DIR,
  "src",
  "builtins",
  "chrome-devtools-mcp.static-input-schemas.json"
)

// Keep this in sync with BROWSER_EXPOSURE_TOOLS in device-protocol. Anything
// not in this allowlist is intentionally not part of Synapse's tool surface
// and won't be advertised; including it here would create noise in the dump.
const ADVERTISED = new Set([
  "list_pages",
  "new_page",
  "navigate_page",
  "navigate_page_history",
  "select_page",
  "close_page",
  "wait_for",
  "take_snapshot",
  "take_screenshot",
  "list_console_messages",
  "click",
  "fill",
  "fill_form",
  "hover",
  "handle_dialog",
  "list_network_requests",
  "get_network_request",
  "performance_start_trace",
  "performance_stop_trace",
  "performance_analyze_insight",
  "evaluate_script",
])

function canonicalize(value) {
  if (value === undefined) return "null"
  if (value === null || typeof value !== "object") return JSON.stringify(value)
  if (Array.isArray(value)) return `[${value.map(canonicalize).join(",")}]`
  const obj = value
  return `{${Object.keys(obj)
    .sort()
    .filter((k) => obj[k] !== undefined)
    .map((k) => `${JSON.stringify(k)}:${canonicalize(obj[k])}`)
    .join(",")}}`
}

const pkgPath = resolve(PKG_DIR, "package.json")
const pinnedVersion = JSON.parse(
  (await import("node:fs")).readFileSync(pkgPath, "utf-8")
).optionalDependencies?.["chrome-devtools-mcp"]
if (!pinnedVersion) {
  throw new Error("chrome-devtools-mcp not in optionalDependencies")
}

const localBin = resolve(
  PKG_DIR,
  "..",
  "..",
  "node_modules",
  ".bin",
  "chrome-devtools-mcp"
)
let command, args
if (existsSync(localBin)) {
  command = localBin
  args = []
} else {
  command = "npx"
  args = ["-y", `chrome-devtools-mcp@${pinnedVersion}`]
}

// Pass only flags chrome-devtools-mcp@0.7.0 actually accepts: --headless and
// --isolated. We deliberately don't pass --no-usage-statistics / category-*
// / --redact-network-headers / --experimentalStructuredContent — they don't
// exist in 0.7.0 and would crash yargs strict mode.
const sidecarArgs = [...args, "--headless=true", "--isolated=true"]

const transport = new StdioClientTransport({
  command,
  args: sidecarArgs,
  env: {
    ...process.env,
    CHROME_DEVTOOLS_MCP_NO_UPDATE_CHECKS: "1",
  },
  stderr: "pipe",
})
const client = new Client(
  { name: "refresh-browser-tool-schemas", version: "0.0.0" },
  { capabilities: {} }
)
await client.connect(transport)
try {
  const { tools } = await client.listTools()
  const schemas = {}
  const hashes = {}
  for (const tool of tools) {
    if (!ADVERTISED.has(tool.name)) continue
    schemas[tool.name] = tool.inputSchema
    hashes[tool.name] = createHash("sha256")
      .update(canonicalize(tool.inputSchema))
      .digest("hex")
  }
  const out = {
    _comment:
      "Static input-schema fallback for chrome-devtools-mcp tools. " +
      "Generated by scripts/refresh-browser-tool-schemas.mjs against the pinned sidecar. " +
      "`schemas` powers describeExposures(); `hashes` powers the runtime drift check.",
    _pinnedVersion: pinnedVersion,
    schemas,
    hashes,
  }
  writeFileSync(OUT, JSON.stringify(out, null, 2) + "\n")
  console.log(`wrote ${Object.keys(schemas).length} schemas + hashes to ${OUT}`)
} finally {
  await client.close()
}
