#!/usr/bin/env node
// Cutover DDL emitter: generates the soft-delete enforcement DDL from the
// manifest + parsed schema, and writes it as a marked section appended to
// schema.sql (between sentinel markers, so re-running replaces it idempotently).
//
// Emits:
//   1. Partial unique indexes (business keys) WHERE deleted_at IS NULL — drops
//      the full-unique constraint and recreates it partial, so a soft-deleted
//      row no longer squats the value (design §8.3). Curated list (business
//      keys only; never the (id, workspace_id) composite-FK targets).
//   2. Existing partial unique indexes re-created with AND deleted_at IS NULL
//      appended (catalog_items / memory_spaces / file_spaces).
//   3. sd_reject_delete() + BEFORE DELETE triggers on every persistent table
//      (class root/junction/child/append-only/reference, excluding immutable=NO,
//      ephemeral, derived, and the 3 BA-owned tables). Bypass: current_user =
//      a privileged owner role (design §7.1/§7.5.1) — NOT a GUC.
//   4. sd_assert_parent_live() + BEFORE INSERT/UPDATE triggers for the §7.3
//      reference-integrity matrix: FKs whose referenced table is a soft-delete
//      root (has deleted_at). Fires only on INSERT / FK-col change / revive.
//
// Re-runnable: replaces the region between the sentinels.

import { readFileSync, writeFileSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"
import yaml from "js-yaml"
import { parseSchema } from "./schema-introspect.mjs"

const here = dirname(fileURLToPath(import.meta.url))
const SCHEMA_PATH = resolve(here, "../src/infrastructure/database/schema.sql")
const MANIFEST_PATH = resolve(
  here,
  "../src/infrastructure/database/soft-delete-table-classification.yml"
)

const BEGIN =
  "-- >>> SOFT-DELETE CUTOVER (generated by cutover-emit-ddl.mjs) >>>"
const END = "-- <<< SOFT-DELETE CUTOVER <<<"

const schema = readFileSync(SCHEMA_PATH, "utf8")
const { tables, foreignKeys } = parseSchema(schema)
const manifest = yaml.load(readFileSync(MANIFEST_PATH, "utf8"))
const mTables = manifest.tables

const hasCol = (t, c) => tables.get(t)?.columns.some((x) => x.name === c)

// --- 1. business-key partial uniques (drop full → recreate partial) --------
// Curated: business keys only. NEVER touch (id, workspace_id) composite-FK
// targets. Each entry: { table, constraint, cols, predicate? }
const BUSINESS_UNIQUES = [
  { table: "users", constraint: "users_email_key", cols: "email" },
  { table: "workspaces", constraint: "workspaces_slug_key", cols: "slug" },
  { table: "publishers", constraint: "publishers_slug_key", cols: "slug" },
  {
    table: "account",
    constraint: "uq_account_provider_account",
    cols: "provider_id, account_id",
  },
  {
    table: "installed_skills",
    constraint: "installed_skills_workspace_id_slug_key",
    cols: "workspace_id, slug",
  },
  {
    table: "transport_accounts",
    constraint:
      "transport_accounts_workspace_id_transport_kind_account_key_key",
    cols: "workspace_id, transport_kind, account_key",
  },
]

// --- 2. existing partial uniques to AND deleted_at IS NULL ------------------
// name -> { table, def (full CREATE UNIQUE INDEX body), origPredicate }
const PARTIAL_UNIQUES_EXTEND = [
  {
    name: "uq_catalog_items_global_slug",
    table: "catalog_items",
    cols: "publisher_id, item_kind, slug",
    pred: "workspace_id IS NULL",
  },
  {
    name: "uq_catalog_items_workspace_slug",
    table: "catalog_items",
    cols: "publisher_id, workspace_id, item_kind, slug",
    pred: "workspace_id IS NOT NULL",
  },
  {
    name: "uq_catalog_items_mirror_source",
    table: "catalog_items",
    cols: "mirror_source_id",
    pred: "mirror_source_id IS NOT NULL",
  },
  {
    name: "uq_memory_spaces_scoped",
    table: "memory_spaces",
    cols: "workspace_id, owner_subject_id, scope_subject_id, namespace_key",
    pred: "scope_subject_id IS NOT NULL",
  },
  {
    name: "uq_memory_spaces_unscoped",
    table: "memory_spaces",
    cols: "workspace_id, owner_subject_id, namespace_key",
    pred: "scope_subject_id IS NULL",
  },
  {
    name: "uq_file_spaces_scoped",
    table: "file_spaces",
    cols: "workspace_id, owner_subject_id, scope_subject_id, namespace_key",
    pred: "scope_subject_id IS NOT NULL",
  },
  {
    name: "uq_file_spaces_unscoped",
    table: "file_spaces",
    cols: "workspace_id, owner_subject_id, namespace_key",
    pred: "scope_subject_id IS NULL",
  },
]

// --- 3. persistent tables that get a reject-delete trigger -----------------
const persistentTables = []
for (const [name, e] of Object.entries(mTables)) {
  const isEphemeral = e.class === "ephemeral" || e.derived === true
  const isBaOwned = e.baOwned === true
  if (isEphemeral || isBaOwned) continue
  persistentTables.push(name)
}
persistentTables.sort()

// --- 4. soft-delete-aware FK integrity triggers (matrix) -------------------
// FKs whose referenced table is a soft-delete root (has deleted_at) AND child is
// a persistent (non-ephemeral) table. Skip self-references handled elsewhere.
const integrityFks = foreignKeys.filter((fk) => {
  const parent = mTables[fk.referencedTable]
  const child = mTables[fk.childTable]
  if (!parent || !child) return false
  if (parent.softDelete !== "deleted_at") return false
  if (!hasCol(fk.referencedTable, "deleted_at")) return false
  // Only single-column FKs (composite FK liveness handled via the parent's own
  // reject/live view); keep the trigger set targeted and unambiguous.
  if (fk.childColumns.length !== 1) return false
  // child should be persistent to be worth a DB guard (ephemeral children are
  // short-lived; their refs don't outlive a soft-deleted parent meaningfully).
  const childEphemeral = child.class === "ephemeral" || child.derived === true
  if (childEphemeral) return false
  return true
})

// ---------------------------------------------------------------------------
function emit() {
  const L = []
  L.push(BEGIN)
  L.push(
    "-- Source of truth: soft-delete-table-classification.yml. Regenerate with"
  )
  L.push(
    "-- `node scripts/cutover-emit-ddl.mjs`. See docs/soft-delete-design.md §7."
  )
  L.push("")

  L.push(
    "-- 0. Privileged delete roles (NOLOGIN). SECURITY DEFINER cleanup/purge"
  )
  L.push(
    "-- functions are owned by synapse_purge_fn_owner; the reject-delete guard"
  )
  L.push("-- recognizes these as current_user (design §7.5.1). Idempotent.")
  L.push(`DO $sd_roles$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'synapse_purge_fn_owner') THEN
    CREATE ROLE synapse_purge_fn_owner NOLOGIN;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'synapse_purge_role') THEN
    CREATE ROLE synapse_purge_role NOLOGIN;
  END IF;
END
$sd_roles$;`)
  L.push("")

  L.push(
    "-- 1/2. Partial unique indexes (business keys survive soft delete) ---------"
  )
  for (const u of BUSINESS_UNIQUES) {
    if (!tables.has(u.table)) continue
    const idx = `uq_${u.table}_${u.cols.replace(/[, ]+/g, "_")}_live`
    L.push(`ALTER TABLE ${u.table} DROP CONSTRAINT IF EXISTS ${u.constraint};`)
    L.push(
      `CREATE UNIQUE INDEX IF NOT EXISTS ${idx} ON ${u.table} (${u.cols}) WHERE deleted_at IS NULL;`
    )
  }
  L.push("")
  for (const p of PARTIAL_UNIQUES_EXTEND) {
    if (!tables.has(p.table)) continue
    L.push(`DROP INDEX IF EXISTS ${p.name};`)
    L.push(
      `CREATE UNIQUE INDEX ${p.name} ON ${p.table} (${p.cols}) WHERE (${p.pred}) AND deleted_at IS NULL;`
    )
  }
  L.push("")

  L.push(
    "-- 3. Reject-delete guard: app role cannot hard-delete persistent tables --"
  )
  L.push(
    "-- Bypass only for privileged delete roles (purge / definer-owned fns);"
  )
  L.push("-- keyed on current_user, NOT a forgeable GUC (design §7.5.1).")
  L.push(`CREATE OR REPLACE FUNCTION sd_reject_delete()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  -- current_user is the function owner inside a SECURITY DEFINER purge fn, or
  -- the privileged purge role on a break-glass login. Everyone else is blocked.
  IF current_user IN ('synapse_purge_fn_owner', 'synapse_purge_role') THEN
    RETURN OLD;
  END IF;
  RAISE EXCEPTION 'hard delete of % is forbidden (soft-delete only; use markDeleted/closeSandbox or an offline purge fn)', TG_TABLE_NAME
    USING ERRCODE = 'restrict_violation';
END;
$$;`)
  L.push("")
  for (const t of persistentTables) {
    L.push(`DROP TRIGGER IF EXISTS sd_reject_delete ON ${t};`)
    L.push(
      `CREATE TRIGGER sd_reject_delete BEFORE DELETE ON ${t} FOR EACH ROW EXECUTE FUNCTION sd_reject_delete();`
    )
  }
  L.push("")

  L.push(
    "-- 4. Soft-delete-aware referential integrity: forbid NEW/revived refs to"
  )
  L.push(
    "-- a soft-deleted parent. Fires only on INSERT / FK-col change / revive"
  )
  L.push("-- (design §7.3); failing-active transitions are allowed.")
  L.push(`CREATE OR REPLACE FUNCTION sd_assert_parent_live()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
  v_parent_table CONSTANT text := TG_ARGV[0];
  v_child_col    CONSTANT text := TG_ARGV[1];
  v_parent_col   CONSTANT text := TG_ARGV[2];
  v_fk_value     uuid;
  v_old_value    uuid;
  v_alive        boolean;
BEGIN
  EXECUTE format('SELECT ($1).%I', v_child_col) INTO v_fk_value USING NEW;
  IF v_fk_value IS NULL THEN
    RETURN NEW;
  END IF;
  -- On UPDATE, only re-check when the FK column actually changed (avoids
  -- blocking the delete orchestration's own status flips on the child).
  IF TG_OP = 'UPDATE' THEN
    EXECUTE format('SELECT ($1).%I', v_child_col) INTO v_old_value USING OLD;
    IF v_old_value IS NOT DISTINCT FROM v_fk_value THEN
      RETURN NEW;
    END IF;
  END IF;
  EXECUTE format(
    'SELECT deleted_at IS NULL FROM %I WHERE %I = $1',
    v_parent_table, v_parent_col
  ) INTO v_alive USING v_fk_value;
  IF v_alive IS DISTINCT FROM TRUE THEN
    RAISE EXCEPTION '%.% references soft-deleted %(%) = %', TG_TABLE_NAME, v_child_col, v_parent_table, v_parent_col, v_fk_value
      USING ERRCODE = 'foreign_key_violation';
  END IF;
  RETURN NEW;
END;
$$;`)
  L.push("")
  for (const fk of integrityFks) {
    const child = fk.childTable
    const col = fk.childColumns[0]
    const parent = fk.referencedTable
    const pcol = fk.referencedColumns[0]
    const trg = `sd_fk_live_${child}_${col}`
    L.push(`DROP TRIGGER IF EXISTS ${trg} ON ${child};`)
    L.push(
      `CREATE TRIGGER ${trg} BEFORE INSERT OR UPDATE OF ${col} ON ${child} FOR EACH ROW EXECUTE FUNCTION sd_assert_parent_live('${parent}', '${col}', '${pcol}');`
    )
  }
  L.push("")
  L.push(emitSecurityDefinerFns())
  L.push("")
  L.push(emitLiveViews())
  L.push("")
  L.push(END)
  return L.join("\n")
}

// --- 4.5 SECURITY DEFINER cleanup functions --------------------------------
// Legitimate child/derived/ephemeral hard-deletes (design §7.5/§11) routed
// through owner-privileged functions so the reject-delete guard permits them.
// Each: SECURITY DEFINER, owner = synapse_purge_fn_owner, fixed search_path,
// EXECUTE revoked from PUBLIC and granted to the app role. The app role calls
// these instead of issuing a naked DELETE.
function emitSecurityDefinerFns() {
  const F = []
  F.push(
    "-- 4.5 SECURITY DEFINER controlled-delete functions (design §7.5/§11)."
  )
  F.push(
    "-- app role gets EXECUTE; functions run as synapse_purge_fn_owner so the"
  )
  F.push(
    "-- reject-delete guard permits the delete. Fixed search_path; audited."
  )

  // Each fn: { name, args (sql signature), body (DELETE statement(s)) }
  const FNS = [
    {
      name: "sd_replace_memory_item_parts",
      args: "p_memory_item_id uuid",
      body: "DELETE FROM memory_item_parts WHERE memory_item_id = p_memory_item_id;",
    },
    {
      name: "sd_detach_participant_address",
      args: "p_participant_id uuid, p_transport_address_id uuid",
      body: "DELETE FROM conversation_participant_addresses WHERE conversation_participant_id = p_participant_id AND transport_address_id = p_transport_address_id;",
    },
    {
      name: "sd_detach_device_service",
      args: "p_service_id uuid, p_device_id uuid",
      body: "DELETE FROM device_services WHERE id = p_service_id AND device_id = p_device_id;",
    },
    {
      name: "sd_clear_member_preferences",
      args: "p_workspace_member_id uuid",
      body: "DELETE FROM workspace_member_preferences WHERE workspace_member_id = p_workspace_member_id;",
    },
    {
      name: "sd_replace_actor_model_groups",
      args: "p_actor_id uuid",
      body: "DELETE FROM actor_model_group_assignments WHERE actor_id = p_actor_id;",
    },
    {
      name: "sd_replace_group_actor_assignments",
      args: "p_group_id uuid",
      body: "DELETE FROM actor_model_group_assignments WHERE group_id = p_group_id;",
    },
    {
      name: "sd_replace_plugin_runtime_permissions",
      args: "p_catalog_version_id uuid",
      body: "DELETE FROM plugin_version_runtime_permissions WHERE catalog_version_id = p_catalog_version_id;",
    },
    {
      name: "sd_replace_catalog_item_categories",
      args: "p_catalog_item_id uuid",
      body: "DELETE FROM catalog_item_categories WHERE catalog_item_id = p_catalog_item_id;",
    },
    {
      name: "sd_replace_remote_agent_group_grants",
      args: "p_remote_agent_id uuid",
      body: "DELETE FROM remote_agent_group_interaction_grants WHERE remote_agent_id = p_remote_agent_id;",
    },
    {
      name: "sd_replace_memory_item_chunks",
      args: "p_memory_item_id uuid, p_index_version int",
      body: "DELETE FROM memory_item_chunks WHERE memory_item_id = p_memory_item_id AND index_version = p_index_version;",
    },
    {
      name: "sd_gc_expired_action_tokens",
      args: "",
      body: "DELETE FROM interaction_action_tokens WHERE expires_at < NOW();",
    },
    {
      name: "sd_gc_dispatched_outbox",
      args: "p_older_than timestamptz",
      body: "DELETE FROM realtime_event_outbox WHERE status = 'dispatched' AND created_at < p_older_than;",
    },
    {
      name: "sd_delete_chat_push_token",
      args: "p_token_id uuid",
      body: "DELETE FROM chat_push_tokens WHERE id = p_token_id;",
    },
  ]

  for (const fn of FNS) {
    F.push(`CREATE OR REPLACE FUNCTION ${fn.name}(${fn.args})
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $$
BEGIN
  ${fn.body}
END;
$$;`)
    F.push(
      `ALTER FUNCTION ${fn.name}(${argTypes(fn.args)}) OWNER TO synapse_purge_fn_owner;`
    )
    F.push(
      `REVOKE EXECUTE ON FUNCTION ${fn.name}(${argTypes(fn.args)}) FROM PUBLIC;`
    )
    // EXECUTE granted to the app role at deploy time (the app's DB role name is
    // env-specific); in dev the owning superuser already has EXECUTE.
  }

  // The owner role needs SELECT (to evaluate DELETE ... WHERE) + DELETE on each
  // table its functions touch. Grant both. (SELECT alone is harmless; these are
  // the same tables the app already reads.)
  const ownerTables = [
    "memory_item_parts",
    "conversation_participant_addresses",
    "device_services",
    "workspace_member_preferences",
    "actor_model_group_assignments",
    "plugin_version_runtime_permissions",
    "catalog_item_categories",
    "remote_agent_group_interaction_grants",
    "memory_item_chunks",
    "interaction_action_tokens",
    "realtime_event_outbox",
    "chat_push_tokens",
  ]
  F.push(
    `GRANT SELECT, DELETE ON ${ownerTables.join(", ")} TO synapse_purge_fn_owner;`
  )
  return F.join("\n")
}

// Extract just the type list from a "p_x uuid, p_y int" signature.
function argTypes(args) {
  if (!args.trim()) return ""
  return args
    .split(",")
    .map((a) => a.trim().split(/\s+/).slice(1).join(" "))
    .join(", ")
}

// --- 5. live views ---------------------------------------------------------
// One <t>_live view per soft-delete root (deleted_at IS NULL); per status table
// (status IN liveValues); plus device child derived views (join devices_live so
// soft-closed sandbox device children disappear, design §8.6). Junction/
// workspace parent-liveness is layered in for the membership tables.
function emitLiveViews() {
  const V = []
  V.push(
    "-- 5. Live views: canonical read surface that hides soft-deleted rows."
  )
  V.push(
    "-- Single-table views over a base table are auto-updatable; WITH CASCADED"
  )
  V.push(
    "-- CHECK OPTION blocks inserting/surfacing a row outside the predicate."
  )

  // roots: deleted_at IS NULL
  const roots = Object.entries(mTables)
    .filter(([, e]) => e.softDelete === "deleted_at")
    .map(([n]) => n)
    .sort()
  for (const t of roots) {
    V.push(`DROP VIEW IF EXISTS ${t}_live;`)
    V.push(
      `CREATE VIEW ${t}_live AS SELECT * FROM ${t} WHERE deleted_at IS NULL WITH CASCADED CHECK OPTION;`
    )
  }

  // status tables: status IN (liveValues). workspace_members additionally needs
  // parent-liveness folded in by callers via the helper; the base _live view
  // here is the status filter.
  const statusTables = Object.entries(mTables)
    .filter(([, e]) => e.softDelete === "status")
    .map(([n, e]) => ({ n, live: e.liveValues || ["active"] }))
    .sort((a, b) => a.n.localeCompare(b.n))
  for (const { n, live } of statusTables) {
    const inList = live.map((v) => `'${v}'`).join(", ")
    V.push(`DROP VIEW IF EXISTS ${n}_live;`)
    V.push(
      `CREATE VIEW ${n}_live AS SELECT * FROM ${n} WHERE status IN (${inList}) WITH CASCADED CHECK OPTION;`
    )
  }

  // device child derived views (design §8.6) — hide children of a soft-closed
  // device. Join back to devices via the documented chain.
  V.push(
    "-- device child derived views (§8.6): hide children of soft-closed devices."
  )
  V.push(`DROP VIEW IF EXISTS device_services_live;`)
  V.push(
    `CREATE VIEW device_services_live AS
  SELECT s.* FROM device_services s
  JOIN devices d ON d.id = s.device_id
  WHERE d.deleted_at IS NULL;`
  )
  V.push(`DROP VIEW IF EXISTS device_exposures_live;`)
  V.push(
    `CREATE VIEW device_exposures_live AS
  SELECT x.* FROM device_exposures x
  JOIN devices d ON d.id = x.device_id
  WHERE d.deleted_at IS NULL;`
  )
  V.push(`DROP VIEW IF EXISTS device_capabilities_live;`)
  V.push(
    `CREATE VIEW device_capabilities_live AS
  SELECT c.* FROM device_capabilities c
  JOIN device_exposures x ON x.id = c.exposure_id
  JOIN devices d ON d.id = x.device_id
  WHERE d.deleted_at IS NULL;`
  )
  V.push(`DROP VIEW IF EXISTS device_tools_live;`)
  V.push(
    `CREATE VIEW device_tools_live AS
  SELECT t.* FROM device_tools t
  JOIN device_exposures x ON x.id = t.exposure_id
  JOIN devices d ON d.id = x.device_id
  WHERE d.deleted_at IS NULL;`
  )

  return V.join("\n")
}

const region = emit()
let out
if (schema.includes(BEGIN) && schema.includes(END)) {
  // Use a replacement FUNCTION so `$$` (dollar-quoted fn bodies) in `region` is
  // not interpreted as a String.replace special pattern.
  out = schema.replace(
    new RegExp(
      `${BEGIN.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${END.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}`
    ),
    () => region
  )
} else {
  out = schema.trimEnd() + "\n\n" + region + "\n"
}
writeFileSync(SCHEMA_PATH, out)
console.log(
  `✓ cutover DDL emitted: ${BUSINESS_UNIQUES.length} business partial-uniques, ${PARTIAL_UNIQUES_EXTEND.length} extended, ${persistentTables.length} reject-delete triggers, ${integrityFks.length} FK-liveness triggers.`
)
