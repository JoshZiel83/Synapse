#!/usr/bin/env node
// cutover-emit-purge: generates the offline-purge SECURITY DEFINER functions
// (design §9) and writes them into schema.sql between dedicated sentinels.
//
// Purge model: FKs are all non-cascading (RESTRICT/SET NULL/NO ACTION), so a
// hard purge must delete in dependency order. The cyclic part of the FK graph is
// broken by first NULLing the nullable (SET NULL) cross-table edges; the
// remaining RESTRICT/NO-ACTION graph is acyclic and yields a full 155-table
// topological order (children before parents).
//
// Emits:
//   - sd_purge_workspace(p_workspace_id uuid): tenant hard-erase (tier B, §5.2).
//     NULLs nullable edges then deletes every row reachable from the workspace
//     (workspace-scoped tables) in leaf→root order. SECURITY DEFINER, owner =
//     synapse_purge_fn_owner (reject-delete guard permits), fixed search_path,
//     writes an audit_logs deletion-ledger row first.
//   - sd_purge_expired_soft_deleted(p_before timestamptz): tier-A retention
//     purge — physically removes rows soft-deleted before the cutoff, leaf→root,
//     EXCLUDING the never-purge set (access_subjects / transport_addresses /
//     audit_logs).

import { readFileSync, writeFileSync } from "node:fs"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"
import { parseSchema } from "./schema-introspect.mjs"

const here = dirname(fileURLToPath(import.meta.url))
const SCHEMA_PATH = resolve(here, "../src/infrastructure/database/schema.sql")

const BEGIN =
  "-- >>> SOFT-DELETE PURGE (generated by cutover-emit-purge.mjs) >>>"
const END = "-- <<< SOFT-DELETE PURGE <<<"

const schema = readFileSync(SCHEMA_PATH, "utf8")
const { tables, foreignKeys } = parseSchema(schema)
const allT = new Set(tables.keys())
const hasCol = (t, c) => tables.get(t)?.columns.some((x) => x.name === c)

// Nullable cross-table edges (SET NULL ⇒ column is nullable) — null these first.
const nullableEdges = foreignKeys.filter(
  (fk) =>
    fk.onDelete === "SET NULL" &&
    fk.childTable !== fk.referencedTable &&
    allT.has(fk.childTable) &&
    allT.has(fk.referencedTable)
)

// Topological order over the non-nullable, non-self edges (children first).
function topoOrder() {
  const edges = foreignKeys.filter(
    (fk) =>
      fk.onDelete !== "SET NULL" &&
      fk.childTable !== fk.referencedTable &&
      allT.has(fk.childTable) &&
      allT.has(fk.referencedTable)
  )
  const referencedBy = new Map([...allT].map((t) => [t, new Set()]))
  for (const fk of edges)
    referencedBy.get(fk.referencedTable).add(fk.childTable)
  const remaining = new Set(allT)
  const order = []
  let guard = 0
  while (remaining.size && guard++ < 500) {
    const deletable = [...remaining].filter((t) =>
      [...referencedBy.get(t)].every((c) => !remaining.has(c))
    )
    if (!deletable.length)
      throw new Error(`purge topo cycle: ${[...remaining]}`)
    // deterministic order within a layer
    deletable.sort()
    for (const t of deletable) {
      order.push(t)
      remaining.delete(t)
    }
  }
  return order
}

const ORDER = topoOrder() // leaf → root

// Never-purge set (tier A retention): immutable registries + audit.
const NEVER_PURGE = new Set([
  "access_subjects",
  "transport_addresses",
  "audit_logs",
])

// Tables that carry a workspace_id (purge-by-workspace surface for tier B).
const WS_TABLES = ORDER.filter((t) => hasCol(t, "workspace_id"))
// Tables with deleted_at (tier A retention surface).
const SD_TABLES = ORDER.filter(
  (t) => hasCol(t, "deleted_at") && !NEVER_PURGE.has(t)
)

function emit() {
  const L = []
  L.push(BEGIN)
  L.push(
    "-- Offline purge functions (design §9). Owner = synapse_purge_fn_owner"
  )
  L.push(
    "-- (NOLOGIN); the reject-delete guard recognizes current_user. These are"
  )
  L.push(
    "-- the ONLY sanctioned hard-delete path for persistent business data."
  )
  L.push("-- Regenerate with `node scripts/cutover-emit-purge.mjs`.")
  L.push("")

  // tier B: tenant hard-erase
  L.push(
    "-- Tier B: tenant hard-erase. NULLs nullable edges, then deletes every"
  )
  L.push(
    "-- workspace-scoped row leaf→root. Irreversible; writes a ledger row."
  )
  const wsNullable = nullableEdges.filter((fk) =>
    hasCol(fk.childTable, "workspace_id")
  )
  L.push(`CREATE OR REPLACE FUNCTION sd_purge_workspace(p_workspace_id uuid)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $$
DECLARE
  v_total bigint := 0;
  v_n bigint;
BEGIN
  -- ledger first (audit_logs is never purged). workspace_id is NULL because the
  -- workspace is (already) soft-deleted and the FK-liveness trigger forbids a new
  -- audit_logs row pointing at a soft-deleted workspace; the id is in resource_id.
  INSERT INTO audit_logs (workspace_id, action, resource_type, resource_id, details)
  VALUES (NULL, 'tenant.hard_erase', 'workspace', p_workspace_id,
          jsonb_build_object('workspace_id', p_workspace_id, 'purged_at', NOW()));

  -- 1. break cycles: null nullable cross-table FKs for this workspace's rows
${wsNullable
  .map(
    (fk) =>
      `  UPDATE ${fk.childTable} SET ${fk.childColumns[0]} = NULL WHERE workspace_id = p_workspace_id AND ${fk.childColumns[0]} IS NOT NULL;`
  )
  .join("\n")}

  -- 2. delete workspace-scoped rows leaf→root
${WS_TABLES.filter((t) => t !== "workspaces")
  .map(
    (t) =>
      `  DELETE FROM ${t} WHERE workspace_id = p_workspace_id; GET DIAGNOSTICS v_n = ROW_COUNT; v_total := v_total + v_n;`
  )
  .join("\n")}

  -- 3. finally the workspace row itself
  DELETE FROM workspaces WHERE id = p_workspace_id;

  INSERT INTO audit_logs (workspace_id, action, resource_type, resource_id, details)
  VALUES (NULL, 'tenant.hard_erase.done', 'workspace', p_workspace_id,
          jsonb_build_object('rows_deleted', v_total, 'finished_at', NOW()));
END;
$$;`)
  L.push(
    "ALTER FUNCTION sd_purge_workspace(uuid) OWNER TO synapse_purge_fn_owner;"
  )
  L.push("REVOKE EXECUTE ON FUNCTION sd_purge_workspace(uuid) FROM PUBLIC;")
  L.push("")

  // tier A: retention purge of soft-deleted rows older than cutoff.
  L.push(
    "-- Tier A: retention purge. Physically removes rows soft-deleted before"
  )
  L.push(
    "-- p_before, leaf→root, skipping the never-purge registries. Bounded by"
  )
  L.push("-- deleted_at; safe to run repeatedly (idempotent).")
  L.push(`CREATE OR REPLACE FUNCTION sd_purge_expired_soft_deleted(p_before timestamptz)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $$
DECLARE
  v_total bigint := 0;
  v_n bigint;
BEGIN
${SD_TABLES.map(
  (t) =>
    `  DELETE FROM ${t} WHERE deleted_at IS NOT NULL AND deleted_at < p_before; GET DIAGNOSTICS v_n = ROW_COUNT; v_total := v_total + v_n;`
).join("\n")}
  INSERT INTO audit_logs (workspace_id, action, resource_type, resource_id, details)
  VALUES (NULL, 'soft_delete.retention_purge', 'system', NULL,
          jsonb_build_object('before', p_before, 'rows_deleted', v_total, 'finished_at', NOW()));
  RETURN v_total;
END;
$$;`)
  L.push(
    "ALTER FUNCTION sd_purge_expired_soft_deleted(timestamptz) OWNER TO synapse_purge_fn_owner;"
  )
  L.push(
    "REVOKE EXECUTE ON FUNCTION sd_purge_expired_soft_deleted(timestamptz) FROM PUBLIC;"
  )
  L.push("")

  // owner needs DELETE + UPDATE + SELECT on every workspace/soft-delete table.
  const ownerTables = [
    ...new Set([...WS_TABLES, ...SD_TABLES, "workspaces"]),
  ].sort()
  L.push(
    `GRANT SELECT, UPDATE, DELETE ON ${ownerTables.join(", ")} TO synapse_purge_fn_owner;`
  )
  L.push("GRANT INSERT ON audit_logs TO synapse_purge_fn_owner;")
  L.push("")
  L.push(END)
  return L.join("\n")
}

const region = emit()
let out
if (schema.includes(BEGIN) && schema.includes(END)) {
  out = schema.replace(
    new RegExp(
      `${BEGIN.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${END.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}`
    ),
    () => region
  )
} else {
  out = schema.trimEnd() + "\n\n" + region + "\n"
}
writeFileSync(SCHEMA_PATH, out)
console.log(
  `✓ purge DDL emitted: sd_purge_workspace (${WS_TABLES.length} ws tables, ${nullableEdges.filter((fk) => hasCol(fk.childTable, "workspace_id")).length} cycle-breaks), sd_purge_expired_soft_deleted (${SD_TABLES.length} soft-delete tables).`
)
