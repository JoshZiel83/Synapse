#!/usr/bin/env bash
#
# Synapse one-click installer (Linux / macOS; re-execs PowerShell on Windows).
#
# WHAT: bootstraps a Node.js runtime that satisfies @synapse package engines,
#       installs @synapse/device-runtime or @synapse/remote-agent-daemon from
#       the private registry, then pairs the device / starts the daemon.
# WHY:  the @synapse npm packages need Node + a configured @synapse:registry
#       BEFORE they can run; this script supplies that bootstrap step.
#
# This file is the canonical source. The API serves it at
#   GET /api/v1/install.sh
# after substituting the @@SYNAPSE_*@@ placeholders with the live instance
# values. The Node sha256 manifest between the SYNAPSE_NODE_MANIFEST markers is
# generated by scripts/installer/generate-node-manifest.mjs.
#
# SECURITY: Node binaries are downloaded to a file and verified against the
# embedded sha256 (sourced from canonical nodejs.org, never from a mirror)
# before use. The whole body is wrapped in __main()/__main "$@" so a truncated
# download never executes a partial script.
#
# bash 3.2 compatible (macOS /bin/bash): no associative arrays, no mapfile, no
# ${var,,}. Knobs are SYNAPSE_*-prefixed; state-changing ops go through run()
# so SYNAPSE_INSTALL_DRY_RUN / --dry-run yields a hermetic, testable trace.

set -euo pipefail

# --- temp cleanup registry -------------------------------------------------
# A single EXIT trap removes every registered temp path. Functions must NOT
# put their own temp dirs in a `local` referenced by a trap: the trap runs in
# global scope at process exit, where a function-local is out of scope and (under
# set -u) would be an "unbound variable". Register via track_tmp instead.
SYNAPSE_TMP_PATHS=""
track_tmp() { SYNAPSE_TMP_PATHS="$SYNAPSE_TMP_PATHS $1"; }
# shellcheck disable=SC2064
trap 'for _p in $SYNAPSE_TMP_PATHS; do rm -rf "$_p" 2>/dev/null || true; done' EXIT

# --- server-rendered placeholders (substituted by the API route) ----------
SYNAPSE_RENDERED_SERVER_URL="@@SYNAPSE_SERVER_URL@@"
SYNAPSE_RENDERED_PRIVATE_REGISTRY="@@SYNAPSE_NPM_REGISTRY@@"
# sha256 of the rendered install.ps1, injected so the Git-Bash → PowerShell
# re-exec path can verify the downloaded ps1 before running it.
SYNAPSE_RENDERED_PS1_SHA256="@@SYNAPSE_PS1_SHA256@@"

# >>> SYNAPSE_NODE_MANIFEST (generated — do not edit by hand) >>>
INSTALLER_NODE_VERSION="24.16.0"
