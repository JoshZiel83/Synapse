# Synapse one-click installer (Windows / PowerShell).
#
# WHAT: bootstraps a Node.js runtime satisfying @synapse engines, installs
#       @synapse/device-runtime or @synapse/remote-agent-daemon from the
#       private registry, then pairs the device / starts the daemon.
# WHY:  the @synapse npm packages need Node + a configured @synapse:registry
#       before they can run; this supplies that bootstrap step.
#
# Canonical source. The API serves it at GET /api/v1/install.ps1 after
# substituting the @@SYNAPSE_*@@ placeholders. The Node sha256 manifest in the
# SYNAPSE_NODE_MANIFEST block is generated by
# scripts/installer/generate-node-manifest.mjs (shared with install.sh).
#
# SECURITY: Node zip is downloaded to a file (never iex'd) and verified against
# the embedded sha256 before extraction. User PATH is persisted via
# [Environment]::SetEnvironmentVariable(...,'User') — NOT setx (which truncates).

[CmdletBinding()]
param(
  [ValidateSet('device', 'daemon')]
  [string]$Target,
  [string]$Server,
  [string]$Code,
  [string]$ApiKey,
  [ValidateSet('cn', 'intl')]
  [string]$Region,
  [string]$Mirror,
  [string]$ToolchainMirror,
  [switch]$NoModifyPath,
  [switch]$WriteUserNpmrc,
  [switch]$PreferPrivateCache,
  [switch]$DryRun
)

$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'
# Windows PowerShell 5.1 defaults to TLS1.0; force TLS1.2 before any web call.
if ($PSVersionTable.PSVersion.Major -lt 6) {
  try { [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12 } catch {}
}

# --- server-rendered placeholders ------------------------------------------
# The API route replaces each @@...@@ token with a fully PowerShell-quoted
# literal (e.g. 'https://host/'), so do NOT add surrounding quotes here.
$RenderedServerUrl = @@SYNAPSE_SERVER_URL@@
$RenderedPrivateRegistry = @@SYNAPSE_NPM_REGISTRY@@

# >>> SYNAPSE_NODE_MANIFEST (generated — do not edit by hand) >>>
$InstallerNodeVersion = '24.16.0'
$NodeArtifactSha256 = @{
